package cloud.trotter.census.contract.auth

/** Canonical lowercase UUID v4 grammar shared by enrollment and bearer parsing. */
object InstallIdGrammar {
    private val canonicalV4 = Regex("[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}")

    fun isCanonicalV4(value: String): Boolean = canonicalV4.matches(value)
}
